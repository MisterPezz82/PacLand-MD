// Build the Z80 program with the bundled SDCC assembler and write it as a C
// array for the 68000 build: build/z80_bin.c. Run by tools/build.mjs.
//   default:          src/z80/player.s, the sound player (hand-written Z80)
//   PL_MUSIC=c:       src/z80/ymq.s, the YM2612 write queue used when the
//                     player runs on the 68000 (src/z80/musdrv.c, the
//                     reference the Z80 player is checked against)
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const req = createRequire(path.join(root, 'package.json'));
const sdccPath = path.join(path.dirname(req.resolve('romdevtools/package.json')), 'src/toolchains/sdcc/sdcc.js');
const {runSdasz80, runSdld, ihxToBin} = await import(pathToFileURL(sdccPath).href);
const ref = process.env.PL_MUSIC === 'c';
const file = ref ? 'src/z80/ymq.s' : 'src/z80/player.s';
const a = await runSdasz80({source: fs.readFileSync(path.join(root, file), 'utf8')});
if (a.exitCode !== 0 || !a.rel) { console.error(a.log); process.exit(1); }
const LIMIT = 0x1400;                       // log buffer (include/musdrv.h Z_LOG) above
const link = async dataLoc => {
  const l = await runSdld({objects: {}, port: 'z80', codeLoc: 0x0040, dataLoc, crt0: a.rel});
  if (l.exitCode !== 0 || !l.ihx) { console.error(l.log); process.exit(1); }
  const sz = {};
  for (const m of (l.map || '').matchAll(/^(_\w+)\s+([0-9A-F]{8})\s+([0-9A-F]{8})/gm)) sz[m[1]] = [parseInt(m[2], 16), parseInt(m[3], 16)];
  return {l, sz};
};
let {l, sz} = await link(0x1000);
let codeEnd = sz._CODE ? sz._CODE[0] + sz._CODE[1] : 0x40;
for (const m of l.ihx.matchAll(/^:([0-9A-F]{2})([0-9A-F]{4})00/gim)) codeEnd = Math.max(codeEnd, parseInt(m[2], 16) + parseInt(m[1], 16));   // absolute code too
const dataLoc = (codeEnd + 15) & ~15;
({l, sz} = await link(dataLoc));
const dataEnd = sz._DATA ? sz._DATA[0] + sz._DATA[1] : dataLoc;
if (dataEnd > LIMIT) { console.error(`Z80 program too big: code to ${codeEnd.toString(16)}h, data to ${dataEnd.toString(16)}h`); process.exit(1); }
const bin = Buffer.from(ihxToBin(l.ihx, codeEnd, 0));
fs.mkdirSync(path.join(root, 'build'), {recursive: true});
fs.writeFileSync(path.join(root, 'build/z80_bin.c'), [`/* GENERATED by tools/build_z80.mjs from ${file}: do not edit. */`,
  '#include <genesis.h>', `const u16 z80_bin_size = ${codeEnd};`,
  `const u8 z80_bin[${codeEnd}] = {` + Array.from(bin).join(',') + '};'].join('\n') + '\n');
console.error(`Z80 ${ref ? 'queue' : 'player'}: code ${codeEnd} bytes, data ${dataLoc.toString(16)}h-${dataEnd.toString(16)}h`);
