"""Strict, local-only Pac-Land parent ROM validation and graphics decoding.

Graphics addresses are bit addresses, MSB first, as in MAME gfxdecode.
No network access. Never accepts a wrong revision silently.
"""
import argparse
import hashlib
import json
from pathlib import Path
import zipfile
import zlib
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]

def load_regions(rom, rules=None):
    rules = rules or json.loads((ROOT/'tools/rom_layout.json').read_text())
    result, audit = {}, []
    archive = zipfile.ZipFile(rom) if Path(rom).is_file() else None
    names = {Path(n).name.lower(): n for n in archive.namelist()} if archive else {}
    try:
        for region, spec in rules['regions'].items():
            data = bytearray(spec['size'])
            for entry in spec['files']:
                name = entry['name']
                raw = archive.read(names[name.lower()]) if archive else (Path(rom)/name).read_bytes()
                crc = f'{zlib.crc32(raw):08x}'
                sha = hashlib.sha1(raw).hexdigest()
                if len(raw) != entry['size'] or crc != entry['crc32'] or sha != entry['sha1']:
                    raise ValueError(f'Wrong or corrupt ROM: {name}: size={len(raw)}, CRC={crc}, SHA1={sha}')
                start = entry['offset']
                data[start:start+len(raw)] = raw
                audit.append(dict(name=name, size=len(raw), crc32=crc, sha1=sha, valid=True))
            result[region] = bytes(data)
    finally:
        if archive: archive.close()
    return result, audit

def bit(data, address):
    return (data[address >> 3] >> (7-(address & 7))) & 1

def decode(data, sprite=False):
    if sprite:
        w=h=16; count=len(data)//128; stride=512
        planes=[0,4,len(data)*4,len(data)*4+4]
        xs=[block*64+i for block in range(4) for i in range(4)]
        ys=[i*8 for i in range(8)]+[256+i*8 for i in range(8)]
    else:
        w=h=8; count=len(data)//16; stride=128; planes=[0,4]
        xs=[64+i for i in range(4)]+list(range(4)); ys=[i*8 for i in range(8)]
    return [[[sum(bit(data,n*stride+p+xs[x]+ys[y]) << (len(planes)-1-b)
                    for b,p in enumerate(planes)) for x in range(w)] for y in range(h)] for n in range(count)]

def palettes(proms):
    def resistor(n): return sum(v for i,v in enumerate([14,31,67,143]) if n & (1 << i))
    return [[(resistor(proms[b*256+i]&15), resistor(proms[b*256+i]>>4),
              resistor(proms[1024+b*256+i]&15)) for i in range(256)] for b in range(4)]

def sheet(frames, lut, pal, group=0, sprite=False):
    size=len(frames[0]); cols=16; gap=2; cell=size+gap
    im=Image.new('RGB',(cols*cell,((len(frames)+cols-1)//cols)*cell),(60,60,60))
    for n,frame in enumerate(frames):
        tile=Image.new('RGB',(size,size))
        for y,row in enumerate(frame):
            for x,index in enumerate(row): tile.putpixel((x,y),pal[lut[group*(16 if sprite else 4)+index]])
        im.paste(tile,((n%cols)*cell,(n//cols)*cell))
    return im

def extract(rom, out):
    regions,audit=load_regions(rom);out.mkdir(parents=True,exist_ok=True)
    for name,data in regions.items(): (out/(name+'.bin')).write_bytes(data)
    allpal=palettes(regions['proms'])
    (out/'palettes.json').write_text(json.dumps(allpal))
    (out/'validation.json').write_text(json.dumps({'set':'pacland','files':audit},indent=2))
    for name in ['fg_chars','bg_chars','sprites']:
        frames=decode(regions[name],name=='sprites')
        (out/(name+'.json')).write_text(json.dumps(frames,separators=(',',':')))
        offset={'fg_chars':0x800,'bg_chars':0xc00,'sprites':0x1000}[name]
        lut=regions['proms'][offset:offset+1024]
        sheet(frames,lut,allpal[0],sprite=name=='sprites').save(out/(name+'.png'))
    # CUS30 wave RAM is generated by the MCU, not a dedicated waveform ROM.
    # Export program regions for analysis; do not label arbitrary MCU bytes music.
    (out/'extraction_status.json').write_text(json.dumps({
        'graphics':'decoded: 512 foreground tiles, 512 background tiles, 512 16x16 sprites',
        'palette':'four 256-colour banks and three 1024-byte lookup tables',
        'text':'not decoded; embedded text needs encoding/routine identification',
        'levels':'requires extract_levels.py and reference execution',
        'audio':'MCU programs exported; event sequences and waveform initialization require analysis'
    },indent=2))
    return regions

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--rom',required=True,type=Path)
    p.add_argument('--out',type=Path,default=ROOT/'res/generated/arcade');a=p.parse_args()
    extract(a.rom,a.out);print('Validated and decoded local reference:',a.out)
