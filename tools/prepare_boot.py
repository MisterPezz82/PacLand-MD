"""Build SEGA-style PEZZ82 lettering and native boot-animation assets."""
import math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[1]


def numeral(letter):
    # The supplied SEGA logo font has letters only. Matching double-line
    # numerals are drawn here instead of rendering its missing-glyph symbol.
    im = Image.new('L', (38, 48))
    d = ImageDraw.Draw(im)
    if letter == '8':
        d.polygon([(8,0),(29,0),(37,8),(37,18),(32,24),(37,30),
                   (37,39),(29,47),(8,47),(0,39),(0,30),(5,24),(0,18),(0,8)],fill=255)
        d.rectangle((12,10,25,17),fill=0)
        d.rectangle((12,30,25,37),fill=0)
    else:
        d.polygon([(8,0),(29,0),(37,8),(37,19),(14,36),(37,36),
                   (37,47),(0,47),(0,35),(24,16),(24,11),(13,11),
                   (13,17),(0,17),(0,8)],fill=255)
    inner = im.filter(ImageFilter.MinFilter(7))
    core = im.filter(ImageFilter.MinFilter(9))
    # One-pixel channel inside the strokes, like the logo font's split rails.
    return Image.frombytes('L',im.size,bytes(
        0 if b and not c else a for a,b,c in zip(im.tobytes(),inner.tobytes(),core.tobytes())))


def pack(pixels, width, height, column_major=False):
    words=[]
    tiles=((tx,ty) for tx in range(width//8) for ty in range(height//8)) if column_major else ((tx,ty) for ty in range(height//8) for tx in range(width//8))
    for tx,ty in tiles:
        for y in range(8):
            w=0
            for x in range(8):w=(w<<4)|pixels[ty*8+y][tx*8+x]
            words.append(w)
    return words


def chomp_pcm():
    """Authored alternating waka glides; no arcade sample or ROM wavetable."""
    rate=16000;pcm=[]
    for syllable in range(2):
        phase=0
        for i in range(1536):
            t=i/1536
            envelope=max(0,min(1,t/.018,(.88-t)/.055))
            x=min(1,t/.86)
            frequency=260*2**(2.15*x) if syllable else 1180*2**(-2.15*x)
            total=0
            for _ in range(4):
                phase+=frequency/(rate*4)
                p=math.floor((phase%1)*32)/32
                value=math.sin(2*math.pi*p)+.12*math.sin(6*math.pi*p)
                total+=round(value*7)/7
            pcm.append(round(94*envelope*total/4)&255)
    return pcm


def main():
    # The logo lettering is stored pre-rendered in tools/boot_logo.txt, so no
    # font file is needed and every build draws the same logo.
    rows=[r for r in (ROOT/'tools/boot_logo.txt').read_text().splitlines() if r and not r.startswith('#')]
    small=Image.new('L',(144,30))
    for y,row in enumerate(rows):
        for x,c in enumerate(row):
            if c=='#':small.putpixel((x,y),255)
    mask=Image.new('L',(256,56));mask.paste(small,(56,13))
    outline=mask.filter(ImageFilter.MaxFilter(3))
    pixels=[[0]*256 for _ in range(56)]
    for y in range(56):
        for x in range(256):
            if outline.getpixel((x,y)):pixels[y][x]=8
            if mask.getpixel((x,y)):
                shade=1+min(4,max(0,(x//30+(48-y)//12)//2))
                if (x+y)%20<4:shade=max(1,shade-1)
                pixels[y][x]=shade
    words=pack(pixels,256,56)
    frames=[]
    for slope in (0,.25,.5,1,.5,.25):
        px=[[0]*64 for _ in range(64)]
        for y in range(64):
            for x in range(64):
                dx,dy=x-31.5,y-31.5
                if dx*dx+dy*dy>18*18:continue
                if dx>0 and abs(dy)<=dx*slope:continue
                px[y][x]=10
                if (x-34)**2+(y-23)**2<3:px[y][x]=11
        for ox,oy in ((0,0),(32,0),(0,32),(32,32)):
            frames+=pack([r[ox:ox+32] for r in px[oy:oy+32]],32,32,True)
    # The user-selected waka1 waveform, signed 8-bit/16kHz; its length remains
    # 3072 bytes to preserve the DAC driver's 256-byte loop alignment.
    pcm=chomp_pcm()
    out=ROOT/'build/boot_data.c';out.parent.mkdir(parents=True,exist_ok=True)
    arr=lambda typ,name,vs,align='':f'const {typ} {name}[] {align} = {{'+','.join(hex(v) for v in vs)+'};'
    out.write_text('/* GENERATED by tools/prepare_boot.py. */\n#include <genesis.h>\n'+
                   arr('u32','boot_tiles',words)+'\n'+arr('u32','boot_pac_tiles',frames)+'\n'+
                   arr('u8','boot_chomp',pcm,'__attribute__((aligned(256)))')+'\n')


if __name__=='__main__':main()
