"""Generate cartridge data for the recompiled object system.

Writes res/generated/native/recomp_data.c (arcade-derived, never distributed):
  arcade_main[0x20000]   main-CPU region image read by the recompiled code (ROM6)
  arcade_sprites[]       512 arcade 16x16 sprites as 4 Mega Drive tiles each
                         (column-major TL, BL, TR, BR), raw 4-bit arcade pens
  sprite_lut[1024]       sprite colour LUT PROM (group*16+pen -> palette index,
                         &0x7F == 0x7F is transparent)
  sprite_pal[32][16]     per-round PAL3: indices 1..n keep the native Pac-Man
                         colours, the rest are the most used object colours
                         that the scenery palettes (PAL0-2) do not have
  sprite_map[32][256]    per-round arcade colour -> PAL3 index (unused)
  group_line[32][64]     per round and colour group: palette line (0-3); a
                         group whose colours the scenery lines hold uses that
                         line, so objects drawn over scenery (hill blocks,
                         logs) match it exactly
  group_pens[32][64*16]  per round, group and arcade pen: pen in that line

Object colour usage is measured, not guessed: each round is set up with the
recompiled code (build/recomp-host, mode 3) and run for --frames frames with
the player walking; every sprite drawn is weighted by its visible pixels.
"""
import argparse
import os
from collections import Counter
import json
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from extract_arcade import ROOT, palettes  # noqa: E402
from convert_palettes import cram, rgb, distance  # noqa: E402

SIZE = 0x3800 + 0x400 + 1
BLOCK_POOL = False   # see the block pool note in main()


def cell_hash(key, bits):
    """Multiplicative (Fibonacci) hash; must match rom_cell() in src/objects.c."""
    return ((key * 40503) & 0xFFFF) >> (16 - bits)


def sprite_blocks(ram):
    """Multi-cell entries as (base code, size bits, group)."""
    for i in range(64):
        o = 2 * i
        code, col = ram[0x2700 + o], ram[0x2701 + o]
        y, x = ram[0x2F00 + o], ram[0x2F01 + o]
        fl = ram[0x3700 + o]
        if not (code or col or y or x or fl):
            continue
        s = (fl >> 2) & 3
        if s:
            yield (code + ((fl & 0x80) << 1)) & ~s, s, col & 63


def sprite_entries(ram):
    for i in range(64):
        o = 2 * i
        code, col = ram[0x2700 + o], ram[0x2701 + o]
        y, x = ram[0x2F00 + o], ram[0x2F01 + o]
        fl, xh = ram[0x3700 + o], ram[0x3701 + o]
        if not (code or col or y or x or fl):
            continue
        sprite = code + ((fl & 0x80) << 1)
        sizex, sizey = (fl >> 2) & 1, (fl >> 3) & 1
        sprite &= ~sizex; sprite &= ~(sizey << 1)
        for sy in range(sizey + 1):
            for sx in range(sizex + 1):
                yield sprite + (2 * sy + sx), col & 63


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--frames', type=int, default=1600)
    p.add_argument('--host', type=Path, default=ROOT / ('build/recomp-host.exe' if os.name == 'nt' else 'build/recomp-host'))
    p.add_argument('--deterministic-coverage', action='store_true',
                   help='use the maker budgeted host; wall-clock timeouts fail instead of truncating coverage')
    a = p.parse_args()
    gen = ROOT / 'res/generated'
    zero = ROOT / 'build/zero-ram.bin'
    zero.write_bytes(bytes(0x3800))
    rom = (gen / 'arcade/maincpu.bin').read_bytes()
    prom = (gen / 'arcade/proms.bin').read_bytes()
    pals = palettes(prom)
    sprites = json.loads((gen / 'arcade/sprites.json').read_text())
    manifest = json.loads((gen / 'levels/manifest.json').read_text())
    native = (gen / 'native/data.c').read_text()
    lut = prom[0x1000:0x1400]

    # pen histogram per sprite code (opaque pixels only depend on group)
    pen_hist = [Counter(v for row in s for v in row) for s in sprites]

    lines = ['/* GENERATED by tools/prepare_recomp.py from the user\'s Pac-Land ROMs. Do not distribute. */',
             '#include <genesis.h>', '#include "recomp_data.h"']
    lines.append('const u8 arcade_main[0x20000] __attribute__((aligned(2))) = {' +
                 ','.join(str(b) for b in rom) + '};')
    packed = []
    for s in sprites:
        for tx, ty in ((0, 0), (0, 1), (1, 0), (1, 1)):
            for y in range(8):
                row = s[ty * 8 + y][tx * 8:tx * 8 + 8]
                v = 0
                for pen in row:
                    v = (v << 4) | pen
                packed.append(v)
    lines.append('const u32 arcade_sprites[512*32] = {' + ','.join(hex(v) for v in packed) + '};')
    lines.append('const u8 sprite_lut[1024] = {' + ','.join(str(b) for b in lut) + '};')

    pal_rows, map_rows, report = [], [], []
    line_rows, pen_rows = [], []
    usage = []          # per round, colour group -> CRAM colour -> visible pixels (palette audit, packing)
    round_cells = []
    for stage in manifest:
        n = stage['round'] - 1
        pal = pals[stage['palette_bank']]
        # native PAL3 for this round, as written by prepare_native.py (last 16 entries of palette_n)
        start = native.index(f'const u16 palette_{n}[] = {{') + len(f'const u16 palette_{n}[] = {{')
        native_full = [int(v, 16) for v in native[start:native.index('}', start)].split(',')]
        native_pal = native_full[48:64]
        # keep native PAL3 entries 1..k verbatim (k = last used); sorted, so a black
        # Pac-Man colour (0x000) can only be entry 1 and stays a real colour
        k = max([i for i in range(1, 15) if native_pal[i]] or [0])
        player = native_pal[1:k + 1]
        tmpdir = Path('/dev/shm') if Path('/dev/shm').is_dir() else ROOT / 'build'   # 15-45 MB dumps
        out = tmpdir / f'recomp-usage-{n + 1:02d}.bin'
        walk = -2 if stage['world_end'] < stage['world_start'] else 2   # return trips go left
        subprocess.run([str(a.host), str(gen / 'arcade/maincpu.bin'), str(zero), str(out), str(n), '3',
                        str(a.frames), str(walk)], check=True)
        data = out.read_bytes(); weights = Counter(); seen_cells = set(); seen_blocks = set()
        if a.deterministic_coverage and len(data) != (a.frames + 1) * SIZE:
            raise RuntimeError(f'Primary coverage run for round {n + 1} stopped before all {a.frames} frames')
        gw = {}
        for k in range(len(data) // SIZE):
            ram = data[k * SIZE:k * SIZE + 0x3800]
            for b in sprite_blocks(ram): seen_blocks.add(b)
            for code, group in sprite_entries(ram):
                seen_cells.add((code, group))
                for pen, count in pen_hist[code].items():
                    c = lut[group * 16 + pen]
                    if c & 0x7F != 0x7F:
                        weights[cram(pal[c])] += count
                        gw.setdefault(group, Counter())[cram(pal[c])] += count
        out.unlink()
        # Extra runs only widen the pre-converted cell/block coverage (other
        # jump rhythm, the other direction, longer): fewer run-time conversions.
        for extra_walk, jump, frames, deaths in ((walk, '23', 3000, ''), (-walk, '40', 1500, ''), (walk, '61', 3000, ''),
                                                 (walk, '40', 2000, '1'), (walk, '17', 2000, '1')):
            env = dict(os.environ, RC_JUMP=jump)
            if deaths: env['RC_DEATHS'] = deaths
            try:   # some runs reach a round-end wait the host harness never leaves: keep what was dumped
                subprocess.run([str(a.host), str(gen / 'arcade/maincpu.bin'), str(zero), str(out), str(n), '3',
                                str(frames), str(extra_walk)], check=True, env=env,
                               timeout=120 if a.deterministic_coverage else 3)
            except subprocess.TimeoutExpired:
                if a.deterministic_coverage:
                    raise RuntimeError('Coverage host exceeded 120 seconds; no partial coverage accepted')
                pass
            d2 = out.read_bytes()
            if a.deterministic_coverage and len(d2) % SIZE:
                raise RuntimeError('Coverage host produced an incomplete RAM snapshot')
            for k in range(len(d2) // SIZE):
                ram = d2[k * SIZE:k * SIZE + 0x3800]
                for b in sprite_blocks(ram): seen_blocks.add(b)
                for cg in sprite_entries(ram): seen_cells.add(cg)
            out.unlink()
        # The walking runs never eat a power pellet, so the frightened ghost
        # colours (pens 10/11 of the ghost colour groups 06, 09, 0C, 0F, 12:
        # blue and light blue) are never seen; without them the blue body was
        # mapped to the nearest round colour (brown on orange-sky rounds).
        # Reserve them with a guaranteed weight.
        base = max(weights.values() or [1])
        for g in (0x06, 0x09, 0x0C, 0x0F, 0x12):
            for pen in (10, 11):
                c = lut[g * 16 + pen]
                if c & 0x7F != 0x7F:
                    weights[cram(pal[c])] += base // 4
                    gw.setdefault(g, Counter())[cram(pal[c])] += base // 4
        # The ghosts' own colours (body, eyes: groups 04/05, 07/08, 0A/0B,
        # 0D/0E, 10/11) are kept exact whatever their screen time in the runs:
        # a purple Sue drawn brown is far more visible than a slightly off
        # scenery object.
        for g in (0x04, 0x05, 0x07, 0x08, 0x0A, 0x0B, 0x0D, 0x0E, 0x10, 0x11):
            for pen in range(16):
                c = lut[g * 16 + pen]
                if c & 0x7F != 0x7F:
                    weights[cram(pal[c])] += base
                    gw.setdefault(g, Counter())[cram(pal[c])] += base
        # every group gets a small weight on all its colours (groups the runs
        # never showed still need a sensible line)
        for g in range(64):
            for pen in range(16):
                c = lut[g * 16 + pen]
                if c & 0x7F != 0x7F: gw.setdefault(g, Counter())[cram(pal[c])] += 1
        # scenery lines PAL0-2 (zero entries after the last colour are unused)
        tl = [[v for v in native_full[16 * i + 1:16 * i + 16]] for i in range(3)]
        def used(row):
            last = max([i for i, v in enumerate(row) if v] or [-1])
            return [(i + 1, v) for i, v in enumerate(row) if i <= max(last, 0)]
        tlines = [used(r) for r in tl]
        def line_cost(entries, cw):
            return sum(w * min(distance(rgb(c), rgb(v)) for _, v in entries) for c, w in cw.items())
        tile_best = {}
        for g, cw in gw.items():
            costs = [line_cost(tlines[i], cw) if tlines[i] else 1e18 for i in range(3)]
            b = min(range(3), key=lambda i: (costs[i], i)); tile_best[g] = (costs[b], b)
        # PAL3 is chosen for the colours the scenery lines cannot give
        weights = Counter()
        for g, cw in gw.items():
            if tile_best[g][0] > 0:
                for c, w in cw.items(): weights[c] += w
        # Greedy weighted error minimisation: repeatedly add the seen colour that
        # most reduces sum(weight * distance to nearest palette colour).
        chosen = list(player)
        # Rare rewards and power-pellet states are absent from walking runs.
        # Keep the edible walkers' purple/highlight and normal Sue colour
        # exact instead of letting a round's frequency histogram choose brown.
        protected = {cram(pal[lut[0x39 * 16 + pen]]) for pen in (3, 8)}
        protected.add(cram(pal[lut[0x10 * 16 + 2]]))  # Sue's normal purple stays distinct
        # Retain the existing blue frightened-car guarantee as purple is added.
        for group in (6, 9, 12, 15, 18):
            protected.update(cram(pal[lut[group * 16 + pen]]) for pen in (10, 11))
        for colour in sorted(protected):
            if colour not in chosen: chosen.append(colour)
        assert len(chosen) <= 14

        seen = list(weights)
        best_d = {c: min([distance(rgb(c), rgb(p)) for p in chosen] or [1e9]) for c in seen}
        while len(chosen) < 14 and seen:
            gain = lambda cand: sum(weights[c] * max(0, best_d[c] - distance(rgb(c), rgb(cand))) for c in seen)
            cand = max((c for c in seen if c not in chosen), key=gain, default=None)
            if cand is None or gain(cand) <= 0: break
            chosen.append(cand)
            for c in seen: best_d[c] = min(best_d[c], distance(rgb(c), rgb(cand)))
        row = [0] + chosen + [0] * (14 - len(chosen)) + [native_pal[15]]
        pal_rows.append(row)
        p3 = [(i, row[i]) for i in range(1, 16) if i <= len(chosen) or i == 15]
        gl, gp = [], []
        for g in range(64):
            cw = gw.get(g, Counter())
            c3 = line_cost(p3, cw)
            tb = tile_best.get(g, (0, 3))
            line = 3 if c3 < tb[0] or tb[1] == 3 else tb[1]
            if g in (6, 9, 12, 15, 18, 0x18, 0x39, 0x3A):
                # These protected colours live in PAL3; a low aggregate error
                # on a scenery line must not substitute the key body colour.
                line = 3
            entries = p3 if line == 3 else tlines[line]
            gl.append(line)
            for pen in range(16):
                c = lut[g * 16 + pen]
                if c & 0x7F == 0x7F: gp.append(0); continue
                t = rgb(cram(pal[c]))
                gp.append(min(entries, key=lambda e: (distance(t, rgb(e[1])), e[0]))[0])
        line_rows.append(gl); pen_rows.append(gp)
        usage.append({str(g): {str(c): w for c, w in cw.items()} for g, cw in gw.items()})
        mapping = []
        for c in range(256):
            target = pal[c]
            best = min(range(1, 16), key=lambda i: (distance(target, rgb(row[i])) if (i <= len(chosen) or i == 15) else 1e9, i))
            mapping.append(best)
        map_rows.append(mapping)
        round_cells.append((sorted(seen_cells), gp, sorted(seen_blocks)))
        report.append(dict(round=n + 1, player_colours=len(player), object_colours=len(chosen) - len(player),
                           distinct_object_colours_seen=len(weights),
                           groups_per_line=[gl.count(i) for i in range(4)]))
    lines.append('const u16 sprite_pal[32][16] = {' + ','.join('{' + ','.join(hex(v) for v in r) + '}' for r in pal_rows) + '};')
    lines.append('const u8 sprite_map[32][256] = {' + ','.join('{' + ','.join(str(v) for v in r) + '}' for r in map_rows) + '};')
    lines.append('const u8 group_line[32][64] = {' + ','.join('{' + ','.join(str(v) for v in r) + '}' for r in line_rows) + '};')
    lines.append('const u8 group_pens[32][1024] = {' + ','.join('{' + ','.join(str(v) for v in r) + '}' for r in pen_rows) + '};')
    # Pre-converted object cells: every (code, colour group) seen in the
    # round's run, converted with that round's pen mapping, deduplicated across
    # rounds. The cartridge DMAs these straight from ROM; only cells missing
    # here are converted at run time.
    pool, pool_ix, keys, idxs, starts = [], {}, [], [], [0]
    for cells, mapping, _ in round_cells:
        for code, group in sorted(cells, key=lambda cg: cg[0] | (cg[1] << 9)):
            words = []
            for w in packed[code * 32:code * 32 + 32]:
                v = 0
                for sh in range(28, -1, -4):
                    v = (v << 4) | mapping[group * 16 + ((w >> sh) & 15)]
                words.append(v)
            t = tuple(words)
            if t not in pool_ix: pool_ix[t] = len(pool); pool.append(t)
            keys.append(code | (group << 9)); idxs.append(pool_ix[t])
        starts.append(len(keys))
    lines.append('const u32 cell_pool[%d] __attribute__((aligned(128))) = {' % (len(pool) * 32) +
                 ','.join(hex(v) for t in pool for v in t) + '};')
    lines.append('const u16 cell_keys[%d] = {' % len(keys) + ','.join(str(v) for v in keys) + '};')
    lines.append('const u16 cell_index[%d] = {' % len(idxs) + ','.join(str(v) for v in idxs) + '};')
    lines.append('const u16 cell_round_start[33] = {' + ','.join(str(v) for v in starts) + '};')
    # Per-round open-addressing hash of the same keys (linear probing, load
    # <= 50%): entry = key << 16 | pool cell, 0xFFFFFFFF = empty. One or two
    # probes instead of a 9-step binary search on every cache miss.
    htab, hstart, hmask = [], [], []
    for r in range(32):
        ks = keys[starts[r]:starts[r + 1]]; ix = idxs[starts[r]:starts[r + 1]]
        size, bits = 16, 4
        while size < 2 * len(ks): size *= 2; bits += 1
        t = [0xFFFFFFFF] * size
        for k, i in zip(ks, ix):
            h = cell_hash(k, bits)
            while t[h] != 0xFFFFFFFF: h = (h + 1) & (size - 1)
            t[h] = (k << 16) | i
        hstart.append(len(htab)); hmask.append((size - 1) | ((16 - bits) << 12)); htab += t
    lines.append('const u32 cell_hash[%d] = {' % len(htab) + ','.join(hex(v) for v in htab) + '};')
    lines.append('const u16 cell_hash_start[32] = {' + ','.join(str(v) for v in hstart) + '};')
    lines.append('const u16 cell_hash_mask[32] = {' + ','.join(str(v) for v in hmask) + '};')
    # Pre-converted multi-cell blocks in VDP sprite tile order (column-major,
    # height 2 or 4 tiles), so a 32x32 entry is one DMA from ROM.
    def cell_words(code, group, mapping):
        out = []
        for w in packed[code * 32:code * 32 + 32]:
            v = 0
            for sh in range(28, -1, -4):
                v = (v << 4) | mapping[group * 16 + ((w >> sh) & 15)]
            out.append(v)
        return out
    bpool, bpool_ix, bkeys, bidx, bstarts, bwords = [], {}, [], [], [0], 0
    for _, mapping, blocks in round_cells:
        for code, sz, group in sorted(blocks, key=lambda b: b[0] | (b[1] << 9) | (b[2] << 11)):
            wcells, hcells = 1 + (sz & 1), 1 + (sz >> 1)
            cols = []
            for cx in range(wcells):
                for lx in range(2):
                    for cy in range(hcells):
                        cw = cell_words(code + 2 * cy + cx, group, mapping)
                        cols += cw[lx * 16:lx * 16 + 16]
            t = tuple(cols)
            if t not in bpool_ix: bpool_ix[t] = bwords; bpool.append(t); bwords += len(t)
            bkeys.append(code | (sz << 9) | (group << 11)); bidx.append(bpool_ix[t] // 32)
        bstarts.append(len(bkeys))
    # The block pool duplicates cells that are also in the cell pool (block()
    # assembles a block from them, two DMAs per cell) and no longer fits the
    # 4 MiB ROM next to the title data: it is left empty (BLOCK_POOL = False).
    if not BLOCK_POOL:
        bpool, bkeys, bidx, bstarts, bwords = [tuple([0] * 8)], [0xFFFFFFFF], [0], [0] * 33, 8
    lines.append('const u32 block_pool[%d] __attribute__((aligned(512))) = {' % bwords +
                 ','.join(hex(v) for t in bpool for v in t) + '};')
    lines.append('const u32 block_keys[%d] = {' % len(bkeys) + ','.join(str(v) for v in bkeys) + '};')
    lines.append('const u16 block_index[%d] = {' % len(bidx) + ','.join(str(v) for v in bidx) + '};')
    lines.append('const u16 block_round_start[33] = {' + ','.join(str(v) for v in bstarts) + '};')
    print(f'pre-converted blocks: {len(bkeys)} round entries, {len(bpool)} unique ({bwords * 4 // 1024} KiB)')
    print(f'pre-converted cells: {len(keys)} round entries, {len(pool)} unique ({len(pool) * 128 // 1024} KiB)')
    (gen / 'native/recomp_data.c').write_text('\n'.join(lines) + '\n')
    (gen / 'native/recomp_palette_report.json').write_text(json.dumps(report, indent=1))
    (gen / 'native/object_usage.json').write_text(json.dumps(usage))
    print('recomp data written;', sum(r['object_colours'] for r in report) / 32, 'object colours per round on average')


if __name__ == '__main__':
    main()
