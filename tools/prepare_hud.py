"""HUD text layer data: the arcade foreground characters (2bpp) and their
colours per palette bank, so the cartridge can draw the arcade's own HUD rows
(score, high score, credit, round, time) straight from arcade video RAM.
Writes res/generated/native/hud_data.c (arcade-derived: do not distribute)."""
import json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from extract_arcade import ROOT, palettes  # noqa: E402
from convert_palettes import cram  # noqa: E402

def main():
    gen = ROOT / 'res/generated'
    prom = (gen / 'arcade/proms.bin').read_bytes()
    pals = palettes(prom)
    chars = json.loads((gen / 'arcade/fg_chars.json').read_text())
    manifest = json.loads((gen / 'levels/manifest.json').read_text())
    font = []
    for t in chars:
        for row in t:
            v = 0
            for p in row: v = (v << 2) | (p & 3)
            font += [v >> 8, v & 255]
    colours = []
    for bank in range(4):
        for g in range(256):
            for p in range(4):
                c = prom[0x800 + 4 * g + p]
                colours.append(0xFFFF if (c & 0x7F) == 0x7F else cram(pals[bank][c]))
    banks = [s['palette_bank'] for s in sorted(manifest, key=lambda s: s['round'])]
    out = ['/* GENERATED by tools/prepare_hud.py from the user\'s Pac-Land ROMs. Do not distribute. */',
           '#include <genesis.h>',
           'const u8 hud_font[512 * 16] = {' + ','.join(str(b) for b in font) + '};',
           'const u16 hud_colours[4 * 256 * 4] = {' + ','.join(hex(c) for c in colours) + '};',
           'const u8 hud_bank[32] = {' + ','.join(str(b) for b in banks) + '};']
    (gen / 'native/hud_data.c').write_text('\n'.join(out) + '\n')
    print('hud data written:', len(font), 'font bytes')

    # Namco glyphs in the SDK ASCII slots. Converted offline, not per menu entry.
    menu=[]
    for ch in range(32,128):
     c=chr(ch)
     code=0x1CA+ch-65 if 65<=ch<=90 else 0x1C0+ch-48 if 48<=ch<=57 else {'.':0x1EA,'-':0x1ED,'/':0x1E4,'!':0x1E8,'?':0x1E9,'+':0x1E7,'#':0x1EF}.get(c,0x1EE)
     for y in range(8):
      row=0
      for x in range(8):
       ink=(font[code*16+y*2+(x>>2)]>>(6-2*(x&3)))&3
       if c==':':ink=x in (3,4) and y in (2,3,5,6)
       if c in '<>':ink=x==((y if y<4 else 7-y)+2 if c=='>' else 5-(y if y<4 else 7-y))
       if c in '()':ink=x==((2 if y in (0,7) else 1 if y in (1,6) else 0) if c=='(' else (3 if y in (0,7) else 4 if y in (1,6) else 5))
       row=(row<<4)|(15 if ink else 0)
      menu.append(row)
    with (gen/'native/hud_data.c').open('a') as stream:stream.write('const u32 hud_menu_font[768] = {'+','.join(hex(x)for x in menu)+'};\n')

if __name__ == '__main__':
    main()

