"""Front-tree overlay masks for ghost sprite blocks (private, arcade-derived).

For every 32x32 ghost block a round can draw (from the generated cell hash),
keep each pixel that is on the shape's outer edge, uses the dark line-art
colour (colour table E1h), or uses a pen the arcade draws over its front layer
(opaque below 80h, or F0h-FEh). The result is a byte AND-mask in the same
layout as arcade_sprites/cell_pool, so the cartridge only copies and masks.
"""
import json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / 'res/generated'
OUT = ROOT / 'build/overlay_masks.c'

def ghost(g): return 4 <= g <= 0x12 or g in (0x39, 0x3A)

def main():
    sprites = json.loads((GEN / 'arcade/sprites.json').read_text())
    lut = (GEN / 'arcade/proms.bin').read_bytes()[0x1000:0x1400]
    text = (GEN / 'native/recomp_data.c').read_text()
    body = re.search(r'const u32 cell_hash\[\d*\][^{]*\{([^}]*)\}', text).group(1)
    cells = set()
    for e in (int(x, 0) for x in body.split(',') if x.strip()):
        k = e >> 16
        if k == 0xFFFF: continue
        cells.add((k & 511, (k >> 9) & 63))
    found = {(c & ~3, g) for c, g in cells if ghost(g)}
    # The expiry flash (3Ah) recolours the purple edible frames (39h) at run time.
    found |= {(b, 0x3A) for b, g in found if g == 0x39}
    blocks = sorted(found, key=lambda b: b[0] | b[1] << 9)
    keys, words = [], []
    for base, g in blocks:
        pens = [[sprites[base + 2 * (y >> 4) + (x >> 4)][y & 15][x & 15] for x in range(32)] for y in range(32)]
        row = lut[g * 16:g * 16 + 16]
        opaque = [[(row[p] & 0x7F) != 0x7F for p in r] for r in pens]
        colour = [[o and (row[p] < 0x80 or row[p] >= 0xF0 or row[p] == 0xE1) for p, o in zip(r, orow)]
                  for r, orow in zip(pens, opaque)]
        op = lambda x, y: 0 <= x < 32 and 0 <= y < 32 and opaque[y][x]
        keep = [[opaque[y][x] and (colour[y][x] or not (op(x - 1, y) and op(x + 1, y) and op(x, y - 1) and op(x, y + 1)))
                 for x in range(32)] for y in range(32)]
        if not any(any(r) for r in keep): continue
        keys.append(base | g << 9)
        for cy in range(2):
            for cx in range(2):
                for tx, ty in ((0, 0), (0, 1), (1, 0), (1, 1)):
                    for y in range(8):
                        v = 0
                        for x in range(8):
                            v = (v << 4) | (15 if keep[cy * 16 + ty * 8 + y][cx * 16 + tx * 8 + x] else 0)
                        words.append(v)
    lines = ['/* GENERATED by tools/prepare_overlay_masks.py from the user\'s Pac-Land ROMs. Do not distribute. */',
             '#include <genesis.h>',
             'const u16 ovl_mask_count = %d;' % len(keys),
             'const u16 ovl_mask_keys[%d] = {%s};' % (max(1, len(keys)), ','.join(str(k) for k in keys) or '0'),
             'const u32 ovl_masks[%d] = {%s};' % (max(1, len(words)), ','.join(hex(w) for w in words) or '0')]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n')
    print('overlay masks: %d ghost blocks, %d bytes' % (len(keys), len(words) * 4))

if __name__ == '__main__':
    main()
